#ifndef UTILS_HPP
#define UTILS_HPP

#include <chrono>

inline uint64_t now_ms() {
    const auto now = std::chrono::steady_clock::now().time_since_epoch();
    return std::chrono::duration_cast<std::chrono::milliseconds>(now).count();
}

static const uint64_t SIGNAL_LOST_MS = 3000;

#endif // UTILS_HPP
